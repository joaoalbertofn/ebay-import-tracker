/**
 * Projeção geográfica calibrada para o canvas 1000 x 540:
 * Longitude: -168°W a +180°E -> X: 0 a 1000
 * Latitude:  +76°N a -58°S   -> Y: 0 a 540
 */
export function projectLon(lon: number): number {
  return Number((((lon + 168) / 348) * 1000).toFixed(1));
}

export function projectLat(lat: number): number {
  return Number((((76 - lat) / 134) * 540).toFixed(1));
}

function buildSvgPathFromLonLat(coords: ReadonlyArray<readonly [number, number]>): string {
  if (coords.length === 0) return '';
  return (
    coords
      .map(([lon, lat], idx) => {
        const x = projectLon(lon);
        const y = projectLat(lat);
        return `${idx === 0 ? 'M' : 'L'} ${x} ${y}`;
      })
      .join(' ') + ' Z'
  );
}

